# Makes the table lib/llm/model_pins_data.dart: the commit of each Hugging Face repository the app downloads from and the SHA-256 of its files.
# Run `python3 tool/pin_models.py` from the root of the project (it needs the network), look at what changed in the file, run test/model_pins_test.dart, commit.
import json, hashlib, urllib.request, re, sys
repos = """onnx-community/PaddleOCR-VL-1.5-ONNX onnx-community/Qwen3-0.6B-ONNX Xenova/paraphrase-multilingual-MiniLM-L12-v2 Xenova/all-MiniLM-L6-v2
onnx-community/whisper-tiny onnx-community/whisper-base monkt/paddleocr-onnx breezedeus/pix2text-mfr-1.5
onnx-community/Qwen3.5-0.8B-Text-ONNX onnx-community/Qwen3.5-2B-ONNX onnx-community/Qwen3.5-4B-ONNX onnx-community/Qwen3-1.7B-ONNX
onnx-community/Qwen2.5-0.5B-Instruct onnx-community/Qwen2.5-1.5B-Instruct onnx-community/Qwen3-4B-Instruct-2507-ONNX onnx-community/Qwen3-8B-ONNX onnx-community/Qwen3-14B-ONNX""".split()
def get(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers={'User-Agent':'pin-script'}), timeout=60)
out = {}
for r in repos:
    try:
        info = json.load(get(f'https://huggingface.co/api/models/{r}'))
    except Exception as e:
        print('SKIP', r, e, file=sys.stderr); continue
    rev = info['sha']; files = {}
    url = f'https://huggingface.co/api/models/{r}/tree/{rev}?recursive=1'
    while url:
        resp = get(url)
        for e in json.load(resp):
            if e['type'] != 'file': continue
            p = e['path']
            if e.get('lfs'):
                if not p.endswith('.safetensors'): files[p] = e['lfs']['oid']
            elif (p.split('/')[-1] in ('tokenizer.json','config.json') or p.endswith('dict.txt')) and e['size'] < 40_000_000:
                h = hashlib.sha256()
                with get(f'https://huggingface.co/{r}/resolve/{rev}/{p}') as f:
                    for chunk in iter(lambda: f.read(1<<20), b''): h.update(chunk)
                files[p] = h.hexdigest()
        link = resp.headers.get('Link') or ''
        m = re.search(r'<([^>]+)>;\s*rel="next"', link)
        url = m.group(1) if m else None
    out[r] = {'rev': rev, 'files': files}
    print(r, rev[:8], len(files), file=sys.stderr)
lines = ["// GENERATED by tool/pin_models.py from the Hugging Face API (commit of each repository and the SHA-256 of each file in it); see model_pins.dart for how it is used.", "",
         "/// repository -> (commit, path in the repository -> SHA-256)", "const pinnedRepositories = <String, ({String revision, Map<String, String> files})>{"]
for r, v in sorted(out.items()):
    lines.append(f"  '{r}': (revision: '{v['rev']}', files: {{")
    for p, h in sorted(v['files'].items()): lines.append(f"    '{p}': '{h}',")
    lines.append("  }),")
lines.append("};")
open('lib/llm/model_pins_data.dart', 'w').write("\n".join(lines) + "\n")
