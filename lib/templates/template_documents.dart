import '../l10n/language.dart';

/// The written content of the templates that come with the app. Every word goes through [tr], so a note made from one reads in the
/// language in use. Dates, weekdays and the number of the week are put in when the note is made.

String templateDay(DateTime d) => '${d.year}-${d.month.toString().padLeft(2, '0')}-${d.day.toString().padLeft(2, '0')}';

String templateWeekday(DateTime d) => switch (d.weekday) {
      1 => tr('Monday'),
      2 => tr('Tuesday'),
      3 => tr('Wednesday'),
      4 => tr('Thursday'),
      5 => tr('Friday'),
      6 => tr('Saturday'),
      _ => tr('Sunday'),
    };

/// The ISO number of the week [d] is in.
int templateWeek(DateTime d) {
  final thursday = DateTime.utc(d.year, d.month, d.day).add(Duration(days: 4 - d.weekday));
  final first = DateTime.utc(thursday.year, 1, 1);
  return (thursday.difference(first).inDays ~/ 7) + 1;
}

String _join(List<String> lines) => '${lines.join('\n')}\n';

/// A Markdown table; the first row is the head. [rows] hold the cells as they are to be written (formulas start with `=`).
String _table(List<List<String>> rows) {
  String line(List<String> cells) => '| ${cells.join(' | ')} |';
  return [line(rows.first), line([for (final _ in rows.first) '---']), for (final r in rows.skip(1)) line(r)].join('\n');
}

